# PlatformIO pre-build script: writes the firmware version into src/version_gen.h (generated, not in git).
#   FW_VERSION = `git describe --tags --always --dirty` (e.g. v1.2.0, v1.2.0-3-gabc1234-dirty, abc1234), or "dev"
# The file is rewritten only when the value changes, so unchanged builds are not redone. Python stdlib only.
import os
import subprocess

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    ROOT = env["PROJECT_DIR"]  # noqa: F821
except NameError:  # run by hand: python scripts/version.py
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

OUT = os.path.join(ROOT, "src", "version_gen.h")


def git_version():
    try:
        out = subprocess.run(["git", "describe", "--tags", "--always", "--dirty"], cwd=ROOT,
                             capture_output=True, text=True, timeout=10)
        v = out.stdout.strip()
        if out.returncode == 0 and v and all(c.isalnum() or c in ".-_+" for c in v):
            return v
    except (OSError, subprocess.SubprocessError):
        pass
    return "dev"


def main():
    ver = git_version()
    text = ("// GENERATED by scripts/version.py from `git describe`. Do not edit.\n"
            "#pragma once\n#define FW_VERSION \"%s\"\n" % ver)
    old = None
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8") as f:
            old = f.read()
    if text != old:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("version: %s" % ver)


main()
