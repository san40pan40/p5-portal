# PlatformIO pre-build script: packs the web panel's static files into a C header as gzip byte arrays,
# so the board stores and sends them compressed (served with a gzip Content-Encoding header).
#   src/web/style.css, src/web/app.js  ->  src/web/assets_gz.h   (generated, not in git)
# Comments are stripped first: /* ... */ in CSS, whole-line // in JS. Python stdlib only.
import gzip
import os
import re

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    ROOT = env["PROJECT_DIR"]  # noqa: F821
except NameError:  # run by hand: python scripts/embed_assets.py
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB = os.path.join(ROOT, "src", "web")
OUT = os.path.join(WEB, "assets_gz.h")
ASSETS = [  # (file, C name, comment stripper)
    ("style.css", "STYLE_CSS_GZ", lambda s: re.sub(r"/\*.*?\*/", "", s, flags=re.S)),
    ("app.js", "APP_JS_GZ", lambda s: "\n".join(l for l in s.splitlines() if not l.lstrip().startswith("//"))),
]


def main():
    parts = ["// GENERATED by scripts/embed_assets.py from src/web/style.css and app.js. Do not edit.",
             "#pragma once", "#include <pgmspace.h>", ""]
    for name, cname, strip in ASSETS:
        with open(os.path.join(WEB, name), encoding="utf-8") as f:
            raw = strip(f.read()).strip().encode("utf-8")
        gz = gzip.compress(raw, compresslevel=9, mtime=0)  # mtime=0: same input -> same bytes
        rows = [", ".join("0x%02x" % b for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
        parts.append("// %s: %d bytes -> %d gzipped" % (name, len(raw), len(gz)))
        parts.append("static const uint8_t %s[] PROGMEM = {\n  %s\n};" % (cname, ",\n  ".join(rows)))
        parts.append("")
        print("embed_assets: %s %d -> %d bytes" % (name, len(raw), len(gz)))
    text = "\n".join(parts)
    old = None
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8") as f:
            old = f.read()
    if text != old:  # rewrite only on change, so the build is not redone every time
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


main()
